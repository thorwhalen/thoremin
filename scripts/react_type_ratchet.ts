/**
 * The React layer's type-error ratchet (#201): `npm run typecheck:react`.
 *
 * The React layer (`tsconfig.react.json`) is red under `tsc` by construction: the repo ships
 * no `@types/react`, so a few dozen pre-existing errors live there, and no gate reads them.
 * That is how #192 shipped a `packages/dag` API change that broke `useEngine` with every gate
 * green: `npm run typecheck` excludes the layer, `npm run build` type-erases, and
 * `npm run lint` is known-red, which trains everyone to ignore it.
 *
 * A ratchet converts the known-red signal into a useful one at no cost: it does not ask
 * for a single error to be fixed first, needs no new dependency, and runs in CI only (its own
 * job, so the main gate's runtime and verdict are untouched). The rule is that the error set
 * is EXACTLY the committed one, and the committed one only ever moves down:
 *
 *   - every error is keyed by FILE and TS CODE, counted; the baseline
 *     (`tsconfig.react.baseline.json`) is that table, committed;
 *   - a key whose count exceeds the baseline's, or that the baseline lacks, FAILS the run
 *     as a NEW error, and the diagnostics behind it are printed with their lines;
 *   - a key whose count is below the baseline's FAILS the run too, as a STALE baseline: the
 *     fix that removed the error re-baselines in the same PR (`npm run typecheck:react --
 *     --update`, or `npm run typecheck:react:baseline`). Letting a shrink pass would leave a
 *     slack of one that hides the next new error of the same code in the same file; failing
 *     closes that window to the one PR that fixed it;
 *   - a shrink and a growth that are the same codes and counts at different paths, with the
 *     total unchanged, is a RENAME: the advice is to re-baseline, not to fix;
 *   - in CI, `--against-config=<file>` compares the committed `tsconfig.react.json` with the one
 *     on main: a file main's config covers, that still exists, and that this one no longer
 *     covers FAILS the run (dropping a failing file from `include` would otherwise remove its
 *     errors from the live set and the baseline together, and stay green). A deleted file may
 *     leave; a still-present one may not (#389);
 *   - in CI, `--against=<file>` compares the committed baseline with the one on main (no tsc
 *     run), so a re-baseline that moves a count UP cannot slip in with a PR.
 *
 * The key deliberately carries no line number and no message text: a line moves whenever
 * something is inserted above it, and a message quotes types that change with unrelated
 * edits. Either would turn an innocent edit into a red run. File + code + count catches a
 * new error anywhere, and misses only an error that replaces another of the same code in the
 * same file, which is the trade accepted for a ratchet that never cries wolf.
 *
 * The diagnostics come from the TypeScript compiler API, not from parsing `tsc`'s text
 * output, and the program is built fresh (no incremental state) so the result cannot depend on
 * a stale `.tsbuildinfo`. Adopting `@types/react` (the issue's option 1) drives the baseline
 * to zero, at which point this script is a plain typecheck and may be retired.
 *
 *   npm run typecheck:react                 # compare against the baseline
 *   npm run typecheck:react -- --update     # rewrite the baseline from the current run
 *   npm run typecheck:react -- --against=main-baseline.json   # the committed baseline never grew past that one
 *   npm run typecheck:react -- --against-config=main-tsconfig.react.json   # no file main's config covers is dropped
 *   npm run typecheck:react -- --config=tsconfig.react.json --baseline=tsconfig.react.baseline.json
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import path from 'node:path';
import ts from 'typescript';

/** Per-file, per-code error counts: `{ "src/app/App.tsx": { "TS2345": 2 } }`. */
type ErrorTable = Record<string, Record<string, number>>;

interface Baseline {
  '//': string;
  config: string;
  total: number;
  errors: ErrorTable;
}

interface Keyed {
  file: string;
  code: string;
  text: string;
}

const DEFAULT_CONFIG = 'tsconfig.react.json';
const DEFAULT_BASELINE = 'tsconfig.react.baseline.json';
/** Diagnostics with no file (a bad compiler option, a missing include) are keyed under this. */
const GLOBAL_FILE = '(global)';
const BASELINE_NOTE =
  'GENERATED by `npm run typecheck:react -- --update` (scripts/react_type_ratchet.ts); do not edit. ' +
  'The React layer\'s pre-existing type errors (tsconfig.react.json), per file and TS code. ' +
  'The ratchet fails when the live set differs from this one in either direction (a new error, or a stale ' +
  'baseline after a fix: re-run --update in the fixing PR); CI fails a PR whose baseline grew past main\'s.';

const { values: options } = parseArgs({
  options: {
    update: { type: 'boolean', default: false },
    config: { type: 'string', default: DEFAULT_CONFIG },
    baseline: { type: 'string', default: DEFAULT_BASELINE },
    against: { type: 'string' },
    'against-config': { type: 'string' },
  },
});

const root = process.cwd();

function collectDiagnostics(configFile: string): Keyed[] {
  const configPath = path.resolve(root, configFile);
  const host: ts.ParseConfigFileHost = {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => {
      throw new Error(ts.flattenDiagnosticMessageText(d.messageText, '\n'));
    },
  };
  const parsed = ts.getParsedCommandLineOfConfigFile(configPath, { noEmit: true, incremental: false }, host);
  if (!parsed) throw new Error(`${configFile}: could not be parsed`);
  // The config's own errors (an include that matches nothing, a bad option) ride along as
  // diagnostics, so a broken config fails the run instead of silently shrinking coverage.
  const program = ts.createProgram({
    rootNames: parsed.fileNames,
    options: parsed.options,
    projectReferences: parsed.projectReferences,
    configFileParsingDiagnostics: parsed.errors,
  });
  return ts
    .getPreEmitDiagnostics(program)
    .filter((d) => d.category === ts.DiagnosticCategory.Error)
    .map((d) => keyed(d));
}

function keyed(d: ts.Diagnostic): Keyed {
  const code = `TS${d.code}`;
  const message = ts.flattenDiagnosticMessageText(d.messageText, '\n  ');
  if (!d.file) return { file: GLOBAL_FILE, code, text: `${GLOBAL_FILE}: ${code}: ${message}` };
  const file = path.relative(root, d.file.fileName).split(path.sep).join('/');
  const { line, character } = d.file.getLineAndCharacterOfPosition(d.start ?? 0);
  return { file, code, text: `${file}:${line + 1}:${character + 1}: ${code}: ${message}` };
}

function tabulate(diagnostics: readonly Keyed[]): ErrorTable {
  const table: ErrorTable = {};
  for (const { file, code } of diagnostics) {
    const row = (table[file] ??= {});
    row[code] = (row[code] ?? 0) + 1;
  }
  // Sorted so the committed file is stable across runs and diffs stay readable.
  const sorted: ErrorTable = {};
  for (const file of Object.keys(table).sort()) {
    sorted[file] = Object.fromEntries(Object.entries(table[file]).sort(([a], [b]) => a.localeCompare(b)));
  }
  return sorted;
}

function total(table: ErrorTable): number {
  return Object.values(table).reduce((n, row) => n + Object.values(row).reduce((m, c) => m + c, 0), 0);
}

function readBaseline(file: string): Baseline | undefined {
  const full = path.resolve(root, file);
  if (!existsSync(full)) return undefined;
  return JSON.parse(readFileSync(full, 'utf8')) as Baseline;
}

function writeBaseline(file: string, configFile: string, table: ErrorTable): void {
  const baseline: Baseline = { '//': BASELINE_NOTE, config: configFile, total: total(table), errors: table };
  writeFileSync(path.resolve(root, file), `${JSON.stringify(baseline, null, 2)}\n`);
}

interface Delta {
  file: string;
  code: string;
  now: number;
  was: number;
}

/** Every (file, code) key whose count differs between the two tables, in either direction. */
function differences(current: ErrorTable, baseline: ErrorTable): Delta[] {
  const out: Delta[] = [];
  const files = new Set([...Object.keys(current), ...Object.keys(baseline)]);
  for (const file of [...files].sort()) {
    const codes = new Set([...Object.keys(current[file] ?? {}), ...Object.keys(baseline[file] ?? {})]);
    for (const code of [...codes].sort()) {
      const now = current[file]?.[code] ?? 0;
      const was = baseline[file]?.[code] ?? 0;
      if (now !== was) out.push({ file, code, now, was });
    }
  }
  return out;
}

/** The growth and the shrink are the same codes and counts at other paths: files were renamed. */
function isRename(grown: readonly Delta[], shrunk: readonly Delta[]): boolean {
  const signature = (deltas: readonly Delta[]) =>
    deltas.map((d) => `${d.code}:${Math.abs(d.now - d.was)}`).sort().join(',');
  return grown.length > 0 && grown.length === shrunk.length && signature(grown) === signature(shrunk);
}

/** `--against`: the committed baseline may not exceed the reference one anywhere (no tsc run). */
function checkAgainst(reference: string): number {
  const committed = readBaseline(options.baseline);
  const ref = readBaseline(reference);
  if (!committed) {
    console.error(`typecheck:react: no committed baseline at ${options.baseline}`);
    return 1;
  }
  if (!ref) {
    console.log(`typecheck:react: no reference baseline at ${reference}; nothing to compare the committed one with`);
    return 0;
  }
  const grown = differences(committed.errors, ref.errors).filter((d) => d.now > d.was);
  if (grown.length) {
    console.error(`typecheck:react: FAIL: ${options.baseline} (${committed.total}) grew past ${reference} (${ref.total}); a baseline only ever moves down:`);
    for (const g of grown) console.error(`  ${g.file} ${g.code}: ${g.now} (was ${g.was})`);
    return 1;
  }
  console.log(`typecheck:react: OK: ${options.baseline} (${committed.total}) is within ${reference} (${ref.total}).`);
  return 0;
}

/** The files a tsconfig covers, as the PR's filesystem resolves its globs (a deleted file matches nothing). */
function coveredFiles(configFile: string): Set<string> {
  const configPath = path.resolve(root, configFile);
  const read = ts.readConfigFile(configPath, ts.sys.readFile);
  if (read.error) throw new Error(ts.flattenDiagnosticMessageText(read.error.messageText, '\n'));
  // Parsed as if it sat at the repo root, not in the reference file's directory: the reference
  // is main's config written to a scratch path, but its globs and its `extends` mean "relative
  // to the repo".
  const asAtRoot = path.join(root, path.basename(configFile));
  const parsed = ts.parseJsonConfigFileContent(read.config, ts.sys, root, { noEmit: true }, asAtRoot);
  if (parsed.fileNames.length === 0) throw new Error(`${configFile}: covers no files (${parsed.errors.map((e) => ts.flattenDiagnosticMessageText(e.messageText, ' ')).join('; ')})`);
  return new Set(parsed.fileNames.map((f) => path.relative(root, f).split(path.sep).join('/')));
}

/** `--against-config`: the committed config may not stop covering a still-present file the reference covers. */
function checkAgainstConfig(reference: string): number {
  if (!existsSync(path.resolve(root, reference))) {
    console.log(`typecheck:react: no reference config at ${reference}; nothing to compare the committed one with`);
    return 0;
  }
  const now = coveredFiles(options.config);
  const dropped = [...coveredFiles(reference)].filter((f) => !now.has(f) && existsSync(path.resolve(root, f))).sort();
  if (dropped.length) {
    console.error(`typecheck:react: FAIL: ${options.config} no longer covers ${dropped.length} file(s) ${reference} covers, and they still exist:`);
    for (const f of dropped) console.error(`  ${f}`);
    console.error('Dropping a file from the include hides its errors from the ratchet. Put it back; delete the file to retire it.');
    return 1;
  }
  console.log(`typecheck:react: OK: ${options.config} covers every still-present file ${reference} covers (${now.size} files).`);
  return 0;
}

function main(): number {
  if (options['against-config'] !== undefined) return checkAgainstConfig(options['against-config']);
  if (options.against !== undefined) return checkAgainst(options.against);

  const diagnostics = collectDiagnostics(options.config);
  const current = tabulate(diagnostics);
  const count = total(current);

  if (options.update) {
    writeBaseline(options.baseline, options.config, current);
    console.log(`typecheck:react: wrote ${options.baseline} (${count} errors in ${Object.keys(current).length} files)`);
    return 0;
  }

  const baseline = readBaseline(options.baseline);
  if (!baseline) {
    console.error(`typecheck:react: no baseline at ${options.baseline}; take one with \`npm run typecheck:react -- --update\` (${count} errors now)`);
    return 1;
  }

  const deltas = differences(current, baseline.errors);
  const grown = deltas.filter((d) => d.now > d.was);
  const shrunk = deltas.filter((d) => d.now < d.was);
  const update = `\`npm run typecheck:react -- --update\` and commit ${options.baseline}`;

  if (count === baseline.total && isRename(grown, shrunk)) {
    console.error(`typecheck:react: FAIL: ${count} errors, at the baseline's total, but at other paths (a rename):`);
    for (const d of deltas) console.error(`  ${d.file} ${d.code}: ${d.now} (was ${d.was})`);
    console.error(`Re-baseline (rename): ${update}.`);
    return 1;
  }
  if (grown.length) {
    console.error(`typecheck:react: FAIL: ${count} errors, baseline ${baseline.total}; new errors (file + TS code, count now vs baseline):`);
    for (const g of grown) {
      console.error(`  ${g.file} ${g.code}: ${g.now} (was ${g.was})`);
      // Every diagnostic behind a grown key is a candidate: the new one is among them.
      for (const d of diagnostics.filter((d) => d.file === g.file && d.code === g.code)) console.error(`    ${d.text}`);
    }
    console.error('A React-layer caller no longer matches what it imports, or a new file is red. Fix it; a ratchet is never re-baselined upward.');
  }
  if (shrunk.length) {
    console.error(`typecheck:react: FAIL: stale baseline: ${count} errors, baseline ${baseline.total}; errors the baseline still lists are gone:`);
    for (const d of shrunk) console.error(`  ${d.file} ${d.code}: ${d.now} (was ${d.was})`);
    console.error(`Tighten the ratchet in this PR: ${update}.`);
  }
  if (grown.length || shrunk.length) return 1;

  console.log(`typecheck:react: OK: ${count} errors, at the baseline.`);
  return 0;
}

process.exitCode = main();
