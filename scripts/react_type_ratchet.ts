/**
 * The React layer's type-error ratchet (#201): `npm run typecheck:react`.
 *
 * The React layer (`tsconfig.react.json`) is red under `tsc` by construction: the repo ships
 * no `@types/react`, so a few dozen pre-existing errors live there, and no gate reads them.
 * That is how #192 shipped a `packages/dag` API change that broke `useEngine` with every gate
 * green: `npm run typecheck` excludes the layer, `npm run build` type-erases, and
 * `npm run lint` is known-red, which trains everyone to ignore it.
 *
 * A ratchet converts the known-red signal into a useful one at no cost: it does not ask
 * for a single error to be fixed first, needs no new dependency, and runs in CI only (its own
 * job, so the main gate's runtime and verdict are untouched). The rule is that the error set
 * may shrink but never grow:
 *
 *   - every error is keyed by FILE and TS CODE, counted; the baseline
 *     (`tsconfig.react.baseline.json`) is that table, committed;
 *   - a key whose count exceeds the baseline's, or that the baseline lacks, FAILS the run,
 *     and the diagnostics behind it are printed with their lines;
 *   - a run with fewer errors PASSES and asks for a re-baseline
 *     (`npm run typecheck:react -- --update`, or `npm run typecheck:react:baseline`), so the
 *     ratchet only ever tightens.
 *
 * The key deliberately carries no line number and no message text: a line moves whenever
 * something is inserted above it, and a message quotes types that change with unrelated
 * edits. Either would turn an innocent edit into a red run. File + code + count catches a
 * new error anywhere, and misses only an error that replaces another of the same code in the
 * same file, which is the trade accepted for a ratchet that never cries wolf.
 *
 * The diagnostics come from the TypeScript compiler API, not from parsing `tsc`'s text
 * output, and the program is built fresh (no incremental state) so the result cannot depend on
 * a stale `.tsbuildinfo`. Adopting `@types/react` (the issue's option 1) drives the baseline
 * to zero, at which point this script is a plain typecheck and may be retired.
 *
 *   npm run typecheck:react                 # compare against the baseline
 *   npm run typecheck:react -- --update     # rewrite the baseline from the current run
 *   npm run typecheck:react -- --config=tsconfig.react.json --baseline=tsconfig.react.baseline.json
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import path from 'node:path';
import ts from 'typescript';

/** Per-file, per-code error counts: `{ "src/app/App.tsx": { "TS2345": 2 } }`. */
type ErrorTable = Record<string, Record<string, number>>;

interface Baseline {
  '//': string;
  config: string;
  total: number;
  errors: ErrorTable;
}

interface Keyed {
  file: string;
  code: string;
  text: string;
}

const DEFAULT_CONFIG = 'tsconfig.react.json';
const DEFAULT_BASELINE = 'tsconfig.react.baseline.json';
/** Diagnostics with no file (a bad compiler option, a missing include) are keyed under this. */
const GLOBAL_FILE = '(global)';
const BASELINE_NOTE =
  'GENERATED by `npm run typecheck:react -- --update` (scripts/react_type_ratchet.ts); do not edit. ' +
  'The React layer\'s pre-existing type errors (tsconfig.react.json), per file and TS code. ' +
  'The ratchet fails when a count grows or a key appears; it asks for a re-baseline when one shrinks.';

const { values: options } = parseArgs({
  options: {
    update: { type: 'boolean', default: false },
    config: { type: 'string', default: DEFAULT_CONFIG },
    baseline: { type: 'string', default: DEFAULT_BASELINE },
  },
});

const root = process.cwd();

function collectDiagnostics(configFile: string): Keyed[] {
  const configPath = path.resolve(root, configFile);
  const host: ts.ParseConfigFileHost = {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => {
      throw new Error(ts.flattenDiagnosticMessageText(d.messageText, '\n'));
    },
  };
  const parsed = ts.getParsedCommandLineOfConfigFile(configPath, { noEmit: true, incremental: false }, host);
  if (!parsed) throw new Error(`${configFile}: could not be parsed`);
  const program = ts.createProgram({ rootNames: parsed.fileNames, options: parsed.options, projectReferences: parsed.projectReferences });
  return ts
    .getPreEmitDiagnostics(program)
    .filter((d) => d.category === ts.DiagnosticCategory.Error)
    .map((d) => keyed(d));
}

function keyed(d: ts.Diagnostic): Keyed {
  const code = `TS${d.code}`;
  const message = ts.flattenDiagnosticMessageText(d.messageText, '\n  ');
  if (!d.file) return { file: GLOBAL_FILE, code, text: `${GLOBAL_FILE}: ${code}: ${message}` };
  const file = path.relative(root, d.file.fileName).split(path.sep).join('/');
  const { line, character } = d.file.getLineAndCharacterOfPosition(d.start ?? 0);
  return { file, code, text: `${file}:${line + 1}:${character + 1}: ${code}: ${message}` };
}

function tabulate(diagnostics: readonly Keyed[]): ErrorTable {
  const table: ErrorTable = {};
  for (const { file, code } of diagnostics) {
    const row = (table[file] ??= {});
    row[code] = (row[code] ?? 0) + 1;
  }
  // Sorted so the committed file is stable across runs and diffs stay readable.
  const sorted: ErrorTable = {};
  for (const file of Object.keys(table).sort()) {
    sorted[file] = Object.fromEntries(Object.entries(table[file]).sort(([a], [b]) => a.localeCompare(b)));
  }
  return sorted;
}

function total(table: ErrorTable): number {
  return Object.values(table).reduce((n, row) => n + Object.values(row).reduce((m, c) => m + c, 0), 0);
}

function readBaseline(file: string): Baseline | undefined {
  const full = path.resolve(root, file);
  if (!existsSync(full)) return undefined;
  return JSON.parse(readFileSync(full, 'utf8')) as Baseline;
}

function writeBaseline(file: string, configFile: string, table: ErrorTable): void {
  const baseline: Baseline = { '//': BASELINE_NOTE, config: configFile, total: total(table), errors: table };
  writeFileSync(path.resolve(root, file), `${JSON.stringify(baseline, null, 2)}\n`);
}

/** The (file, code) keys whose current count exceeds the baseline's, with the excess. */
function grown(current: ErrorTable, baseline: ErrorTable): Array<{ file: string; code: string; now: number; was: number }> {
  const out: Array<{ file: string; code: string; now: number; was: number }> = [];
  for (const [file, row] of Object.entries(current)) {
    for (const [code, now] of Object.entries(row)) {
      const was = baseline[file]?.[code] ?? 0;
      if (now > was) out.push({ file, code, now, was });
    }
  }
  return out;
}

function main(): number {
  const diagnostics = collectDiagnostics(options.config);
  const current = tabulate(diagnostics);
  const count = total(current);

  if (options.update) {
    writeBaseline(options.baseline, options.config, current);
    console.log(`typecheck:react: wrote ${options.baseline} (${count} errors in ${Object.keys(current).length} files)`);
    return 0;
  }

  const baseline = readBaseline(options.baseline);
  if (!baseline) {
    console.error(`typecheck:react: no baseline at ${options.baseline}; take one with \`npm run typecheck:react -- --update\` (${count} errors now)`);
    return 1;
  }

  const growth = grown(current, baseline.errors);
  if (growth.length) {
    console.error(`typecheck:react: FAIL: ${count} errors, baseline ${baseline.total}; new errors (file + TS code, count now vs baseline):`);
    for (const g of growth) {
      console.error(`  ${g.file} ${g.code}: ${g.now} (was ${g.was})`);
      // Every diagnostic behind a grown key is a candidate: the new one is among them.
      for (const d of diagnostics.filter((d) => d.file === g.file && d.code === g.code)) console.error(`    ${d.text}`);
    }
    console.error('A React-layer caller no longer matches what it imports, or a new file is red. Fix it; a ratchet is never re-baselined upward.');
    return 1;
  }

  if (count < baseline.total) {
    console.log(`typecheck:react: OK: ${count} errors, down from the baseline's ${baseline.total}. Tighten the ratchet: \`npm run typecheck:react -- --update\` and commit ${options.baseline}.`);
  } else {
    console.log(`typecheck:react: OK: ${count} errors, at the baseline.`);
  }
  return 0;
}

process.exitCode = main();
